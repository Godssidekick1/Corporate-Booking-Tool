// ── npm run db:baseline ──────────────────────────────────────────────────────
// Rewrites schema/baseline.sql: the whole schema as it stands after every
// migration in db/migrations, plus the rows a new database cannot do without:
//
//   schema_migrations   so `npm run migrate` on a new database continues from
//                       here instead of re-running what the baseline holds
//   countries, regions, airports, airlines
//                       reference data, loaded by migrations (and, for
//                       airlines, added to by searches); no tenant's rows
//
// Nothing else: no client, person, booking or sign-in row ever reaches it.
// cities is loaded by scripts/load-cities.mjs on each database instead (14 MB).
//
//   npm run db:baseline                  the local owner: TEST_OWNER_DATABASE_URL,
//                                        else MIGRATE_DATABASE_URL, else DATABASE_URL
//   node scripts/capture-baseline.mjs <url>
//
// Read-only on the database. Refuses one that is behind db/migrations, so the
// baseline and the migrations never disagree. Run after adding a migration
// (and applying it locally); scripts/create-database.mjs builds from it.
// ─────────────────────────────────────────────────────────────────────────────

import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import pg from 'pg'
import { sslFor } from './migrate.mjs'
import { pgTool, connectionFor } from './pg-tools.mjs'

const WITH_DATA = ['schema_migrations', 'countries', 'regions', 'airports', 'airlines']
const OUT = join(process.cwd(), 'schema', 'baseline.sql')
const MIGRATIONS = join(process.cwd(), 'db', 'migrations')

function envValue(name) {
  if (process.env[name]) return process.env[name]
  const envPath = join(process.cwd(), '.env.local')
  if (!existsSync(envPath)) return undefined
  for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const m = line.match(new RegExp(`^\\s*${name}\\s*=\\s*(.*)\\s*$`))
    if (m) return m[1].replace(/^["']|["']$/g, '')
  }
  return undefined
}

const url = process.argv[2] ?? envValue('TEST_OWNER_DATABASE_URL') ?? envValue('MIGRATE_DATABASE_URL') ?? envValue('DATABASE_URL')
if (!url) {
  console.error('[baseline] no database: pass a URL or set TEST_OWNER_DATABASE_URL in .env.local')
  process.exit(1)
}
let target
try {
  target = new URL(url)
} catch {
  console.error('[baseline] the database URL is not a valid URL (special characters in the password must be percent-encoded).')
  process.exit(1)
}

const client = new pg.Client({ connectionString: url, ssl: sslFor(url) })
await client.connect()
let tables
try {
  const applied = new Set((await client.query('select filename from public.schema_migrations')).rows.map(r => r.filename))
  const behind = readdirSync(MIGRATIONS).filter(f => f.endsWith('.sql') && !applied.has(f))
  if (behind.length > 0) {
    console.error(`[baseline] ${target.pathname.slice(1)} is behind db/migrations (${behind.join(', ')}). Run npm run migrate on it first.`)
    process.exit(1)
  }
  tables = (await client.query(`
    select relname from pg_class
     where relnamespace = 'public'::regnamespace and relkind in ('r', 'p')
     order by 1`)).rows.map(r => r.relname)
} finally {
  await client.end()
}

const { args, env } = connectionFor(url)
const dump = spawnSync(pgTool('pg_dump'), [
  ...args,
  '--no-owner',          // whoever builds the new database owns it
  '--no-statistics',
  '--restrict-key=cbtbaseline',   // a fixed key, so a re-capture diffs cleanly
  ...tables.filter(t => !WITH_DATA.includes(t)).map(t => `--exclude-table-data=public.${t}`),
], { env, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 })
if (dump.status !== 0) {
  console.error('[baseline] pg_dump failed:', dump.stderr)
  process.exit(1)
}

const header = `-- ── schema/baseline.sql ─────────────────────────────────────────────────────
-- GENERATED by \`npm run db:baseline\` (scripts/capture-baseline.mjs). Do not
-- edit: change the schema with a migration in db/migrations, apply it, and
-- capture again.
--
-- The schema after every migration, plus the rows of ${WITH_DATA.join(', ')}.
-- No tenant's data. Built into a new, empty database by
-- \`npm run db:create\` (scripts/create-database.mjs), which also creates the
-- cbt_app role its grants name.
-- ─────────────────────────────────────────────────────────────────────────────

`
writeFileSync(OUT, header + dump.stdout.replace(/\r\n/g, '\n'))
const migrations = (dump.stdout.match(/^\d{14}_[^\t\n]+\.sql\t/gm) ?? []).length
console.info(`[baseline] schema/baseline.sql written from ${target.hostname}/${target.pathname.slice(1)}: ` +
  `${tables.length} tables, data for ${WITH_DATA.length} of them, ${migrations} migrations recorded.`)
